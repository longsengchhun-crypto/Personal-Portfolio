alter table public.project_inquiries
  add column if not exists client_response text not null default '',
  add column if not exists last_notification_status varchar(20) not null default '',
  add column if not exists last_notified_at timestamptz;

alter table public.project_inquiries
  drop constraint if exists project_inquiries_last_notification_status_check;

alter table public.project_inquiries
  add constraint project_inquiries_last_notification_status_check
  check (last_notification_status in ('', 'sent', 'not-configured', 'not-applicable', 'failed'));

create table if not exists public.inquiry_messages (
  id bigint generated by default as identity primary key,
  inquiry_id bigint not null references public.project_inquiries(id) on delete cascade,
  message_type varchar(24) not null check (message_type in ('receipt', 'accepted', 'declined', 'reply', 'status')),
  subject varchar(220) not null default '',
  body text not null default '',
  delivery_status varchar(20) not null check (delivery_status in ('sent', 'not-configured', 'not-applicable', 'failed')),
  created_at timestamptz not null default now()
);

create index if not exists inquiry_messages_inquiry_created_idx
on public.inquiry_messages(inquiry_id, created_at desc);

alter table public.inquiry_messages enable row level security;
revoke all on public.inquiry_messages from anon, authenticated;

