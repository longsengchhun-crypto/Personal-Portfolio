    'dashboard_delete_product_category(text,bigint)',
    'dashboard_upsert_product(text,bigint,bigint,text,text,text,text,numeric,numeric,text,text,text,text,text,text,text,text,text,text,text,text,text,text,text,boolean,text,integer)',
    'dashboard_delete_product(text,bigint)',
