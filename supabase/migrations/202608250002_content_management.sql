-- Move Services / Skills / Software from hardcoded lib/content.ts arrays into
-- the database, seeded verbatim from the current hardcoded copy, so admins
-- can edit site content without touching code.

create table public.services (
  id bigint generated by default as identity primary key,
  title varchar(160) not null unique,
  description text not null default '',
  "order" integer not null default 0 check ("order" >= 0),
  is_active boolean not null default true,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table public.skill_groups (
  id bigint generated by default as identity primary key,
  name varchar(80) not null unique,
  "order" integer not null default 0 check ("order" >= 0)
);

create table public.skills (
  id bigint generated by default as identity primary key,
  group_id bigint not null references public.skill_groups(id) on delete cascade,
  name varchar(80) not null,
  "order" integer not null default 0 check ("order" >= 0)
);

create index skills_group_order_idx on public.skills(group_id, "order");

create table public.software_tools (
  id bigint generated by default as identity primary key,
  name varchar(80) not null unique,
  "order" integer not null default 0 check ("order" >= 0)
);

alter table public.services enable row level security;
alter table public.skill_groups enable row level security;
alter table public.skills enable row level security;
alter table public.software_tools enable row level security;

create policy "public reads active services" on public.services for select to anon, authenticated using (is_active);
create policy "public reads skill groups" on public.skill_groups for select to anon, authenticated using (true);
create policy "public reads skills" on public.skills for select to anon, authenticated using (true);
create policy "public reads software tools" on public.software_tools for select to anon, authenticated using (true);

grant select on public.services, public.skill_groups, public.skills, public.software_tools to anon, authenticated;
grant usage, select on all sequences in schema public to anon, authenticated;

