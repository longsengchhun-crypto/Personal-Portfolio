-- Admin read: everything, including inactive services, gated by the same
-- dashboard token pattern as dashboard_snapshot.
create or replace function public.dashboard_content(p_token text)
returns jsonb
language plpgsql
stable
security definer
set search_path = ''
as $$
begin
  if not private.dashboard_token_ok(p_token) then
    raise exception 'unauthorized';
  end if;

  return jsonb_build_object(
    'site_settings', (select to_jsonb(s) from public.site_settings s order by id limit 1),
    'services', coalesce((select jsonb_agg(to_jsonb(x) order by x."order") from (select * from public.services) x), '[]'::jsonb),
    'skill_groups', coalesce((select jsonb_agg(to_jsonb(x) order by x."order") from (select * from public.skill_groups) x), '[]'::jsonb),
    'skills', coalesce((select jsonb_agg(to_jsonb(x) order by x."order") from (select * from public.skills) x), '[]'::jsonb),
    'software_tools', coalesce((select jsonb_agg(to_jsonb(x) order by x."order") from (select * from public.software_tools) x), '[]'::jsonb)
  );
end
$$;

create or replace function public.dashboard_update_site_settings(
  p_token text, p_professional_title text, p_hero_intro text, p_khmer_intro text,
  p_professional_intro text, p_email text, p_phone text, p_location text,
  p_showreel_title text, p_youtube_url text, p_vimeo_url text, p_local_video_url text
) returns boolean language plpgsql security definer set search_path = '' as $$
begin
  if not private.dashboard_token_ok(p_token) then raise exception 'unauthorized'; end if;
  update public.site_settings set
    professional_title = left(trim(coalesce(p_professional_title, '')), 160),
    hero_intro = coalesce(p_hero_intro, ''),
    khmer_intro = left(coalesce(p_khmer_intro, ''), 255),
    professional_intro = coalesce(p_professional_intro, ''),
    email = left(trim(coalesce(p_email, '')), 254),
    phone = left(trim(coalesce(p_phone, '')), 40),
    location = left(trim(coalesce(p_location, '')), 120),
    showreel_title = left(trim(coalesce(p_showreel_title, '')), 160),
    youtube_url = coalesce(p_youtube_url, ''),
    vimeo_url = coalesce(p_vimeo_url, ''),
    local_video_url = coalesce(p_local_video_url, ''),
    updated_at = now()
  where id = (select id from public.site_settings order by id limit 1);
  return found;
end $$;

create or replace function public.dashboard_upsert_service(
  p_token text, p_id bigint, p_title text, p_description text, p_order integer, p_is_active boolean
) returns bigint language plpgsql security definer set search_path = '' as $$
declare result_id bigint;
begin
  if not private.dashboard_token_ok(p_token) then raise exception 'unauthorized'; end if;
  if p_id is null then
    insert into public.services (title, description, "order", is_active)
    values (left(trim(p_title), 160), coalesce(p_description, ''), coalesce(p_order, 0), coalesce(p_is_active, true))
    returning id into result_id;
  else
    update public.services set
      title = left(trim(p_title), 160), description = coalesce(p_description, ''),
      "order" = coalesce(p_order, 0), is_active = coalesce(p_is_active, true), updated_at = now()
    where id = p_id;
    result_id := p_id;
  end if;
  return result_id;
end $$;

create or replace function public.dashboard_delete_service(p_token text, p_id bigint)
returns boolean language plpgsql security definer set search_path = '' as $$
begin
  if not private.dashboard_token_ok(p_token) then raise exception 'unauthorized'; end if;
  delete from public.services where id = p_id;
  return found;
end $$;

