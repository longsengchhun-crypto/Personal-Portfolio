function normalize(text: string) {
  return ` ${text.toLowerCase().replace(/\s+/g, " ")} `;
}

function slugify(name: string) {
  return name.toLowerCase().replace(/[^a-z0-9]+/g, "-").replace(/^-|-$/g, "");
}

function scoreMatch(haystack: string, keywords: string[]) {
  let score = 0;
  for (const keyword of keywords) if (haystack.includes(keyword.toLowerCase())) score += keyword.trim().length;
  return score;
}

export function suggestCategory(input: CategorizationInput, existing: ExistingCategory[]): { categoryId: number } | { newCategoryName: string } | null {
  const haystack = normalize([input.title, input.short_description, input.tags, input.file_formats].filter(Boolean).join(" "));
  if (haystack.trim().length < 2) return null;

  // 1. Reuse an existing category if its own name is already implied by the product's text —
  // keeps the catalog from fragmenting into near-duplicate categories over time.
  let bestExisting: { id: number; score: number } | null = null;
  for (const category of existing) {
    const words = category.name.toLowerCase().split(/[^a-z0-9]+/).filter((w) => w.length > 2 && w !== "3d" && w !== "models");
    const score = scoreMatch(haystack, words);
    if (score > 0 && (!bestExisting || score > bestExisting.score)) bestExisting = { id: category.id, score };
  }
  if (bestExisting) return { categoryId: bestExisting.id };

  // 2. A Cambodian cultural/seasonal theme is more specific than a generic asset type, so it's
  // checked first.
  const themeMatch = pickBest(haystack, CULTURAL_THEMES) ?? pickBest(haystack, GENERIC_TYPES);
  if (!themeMatch) return null;

  const existingBySlug = existing.find((c) => c.slug === slugify(themeMatch));
  return existingBySlug ? { categoryId: existingBySlug.id } : { newCategoryName: themeMatch };
}

function pickBest(haystack: string, table: { keywords: string[]; name: string }[]) {
  let best: { name: string; score: number } | null = null;
  for (const entry of table) {
    const score = scoreMatch(haystack, entry.keywords);
    if (score > 0 && (!best || score > best.score)) best = { name: entry.name, score };
  }
  return best?.name ?? null;
}
