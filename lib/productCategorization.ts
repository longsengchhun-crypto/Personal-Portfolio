// Best-effort auto-categorization for new products. Runs once, at product creation, only when
// the admin hasn't already picked a category — it never overrides a category chosen by hand,
// including an explicit "Uncategorized" on a later edit. Purely keyword-based (no external API,
// no extra cost, no network dependency) — good enough to save the admin a manual step on the
// common cases, with the existing category dropdown always there as the manual override.
//
// Naming follows the convention already used in this store's own categories (e.g. "3D
// Character", "Pchum Ben 3D Models"): a Cambodian cultural/local theme keeps its Khmer term
// (transliterated) in the name, everything else gets a plain English "3D <Type>" name. Category
// slugs are generated by the same DB function used everywhere else
// (`dashboard_upsert_product_category`), which strips non a-z0-9 characters — so this
// deliberately never proposes a name in Khmer script itself, only Khmer terms transliterated
// into Latin letters, to avoid producing a colliding/empty slug.

